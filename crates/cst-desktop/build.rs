use std::fs;
use std::path::{Path, PathBuf};

/// Strict compile-time white-list of `design/asset/*.glsl` shaders (no globbing allowed).
const WHITELISTED_SHADERS: &[(&str, &str)] = &[
    ("blue-hour.glsl", "PS_BLUE_HOUR_DXBC"),
    ("blue-sky.glsl", "PS_BLUE_SKY_DXBC"),
    ("night-sky.glsl", "PS_NIGHT_SKY_DXBC"),
    ("frosted-glass.glsl", "PS_FROSTED_GLASS_DXBC"),
];

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=CST_BUILD_VERSION");
    println!("cargo:rerun-if-env-changed=CST_MANIFEST_REQUIRE_ADMIN");

    let manifest_dir =
        PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let repo_root = manifest_dir
        .parent()
        .and_then(Path::parent)
        .expect("workspace root");
    let design_asset_dir = repo_root.join("design/asset");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));

    for &(file_name, _) in WHITELISTED_SHADERS {
        let p = design_asset_dir.join(file_name);
        println!("cargo:rerun-if-changed={}", p.display());
    }
    println!(
        "cargo:rerun-if-changed={}",
        design_asset_dir.join("blue-hour-palette.png").display()
    );
    println!(
        "cargo:rerun-if-changed={}",
        design_asset_dir
            .join("blue-hour-dark-palette.png")
            .display()
    );

    compile_all_shaders(&design_asset_dir, &out_dir);

    #[cfg(windows)]
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        embed_windows_resources(repo_root, &out_dir);
    }
}

/// Translates each white-listed WebGL ES `#version 100` shader into deterministic GLSL 450
/// (`vec4`-packed `std140` uniform block + local bottom-up `gl_FragCoord` flip), validates & emits
/// Shader Model `5_0` HLSL via `naga`, and compiles DXBC bytecode via Win32 `D3DCompile`.
fn compile_all_shaders(design_asset_dir: &Path, out_dir: &Path) {
    let vs_hlsl = r#"
cbuffer CstVsUniforms : register(b0) {
    float4 u_slot0; // [origin_x, origin_y, width, height]
    float4 u_slot1; // [viewport_w, viewport_h, opacity, time_or_pad]
};

struct VsOut {
    float4 pos : SV_Position;
};

VsOut vs_main(uint vid : SV_VertexID) {
    float2 corner = float2((vid & 1u) != 0u ? 1.0 : 0.0, (vid & 2u) != 0u ? 1.0 : 0.0);
    float2 px = u_slot0.xy + corner * u_slot0.zw;
    float2 vp = max(u_slot1.xy, float2(1.0, 1.0));
    float2 ndc = float2((px.x / vp.x) * 2.0 - 1.0, 1.0 - (px.y / vp.y) * 2.0);
    VsOut o;
    o.pos = float4(ndc, 0.0, 1.0);
    return o;
}
"#;
    let vs_dxbc = d3d_compile_hlsl(vs_hlsl, "vs_main", "vs_5_0", "cst_surface_vs.hlsl");

    let mut rust_out = String::new();
    rust_out.push_str("// @generated by crates/cst-desktop/build.rs — DO NOT EDIT.\n");
    append_byte_const(&mut rust_out, "VS_SURFACE_DXBC", &vs_dxbc);

    for &(file_name, const_name) in WHITELISTED_SHADERS {
        let src_path = design_asset_dir.join(file_name);
        let raw_glsl = fs::read_to_string(&src_path)
            .unwrap_or_else(|e| panic!("failed to read {}: {e}", src_path.display()));
        let glsl_450 = wrap_webgl100_to_glsl450(file_name, &raw_glsl);
        let hlsl = translate_glsl450_to_hlsl50(file_name, &glsl_450);
        // Save intermediate HLSL into OUT_DIR for easy inspection/debugging
        let hlsl_dump = out_dir.join(format!("{file_name}.hlsl"));
        let _ = fs::write(&hlsl_dump, &hlsl);
        let ps_dxbc = d3d_compile_hlsl(&hlsl, "main", "ps_5_0", file_name);
        append_byte_const(&mut rust_out, const_name, &ps_dxbc);
    }

    fs::write(out_dir.join("compiled_shaders.rs"), rust_out)
        .expect("write OUT_DIR/compiled_shaders.rs");
}

fn append_byte_const(out: &mut String, name: &str, bytes: &[u8]) {
    assert!(
        bytes.len() >= 32 && &bytes[0..4] == b"DXBC",
        "{name} did not produce a valid DXBC container"
    );
    out.push_str(&format!("pub const {name}: &[u8] = &{bytes:?};\n"));
}

fn strip_uniform_and_version_lines(raw_glsl: &str) -> String {
    let mut kept = Vec::new();
    for line in raw_glsl.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("#version ")
            || trimmed.starts_with("precision ")
            || (trimmed.starts_with("uniform ") && trimmed.ends_with(';'))
        {
            continue;
        }
        kept.push(line);
    }
    kept.join("\n")
}

fn wrap_webgl100_to_glsl450(file_name: &str, raw_glsl: &str) -> String {
    let stripped = strip_uniform_and_version_lines(raw_glsl);

    let (header, footer_alpha_expr) = match file_name {
        "blue-sky.glsl" | "night-sky.glsl" => (
            r#"#version 450
layout(std140, set = 0, binding = 0) uniform CstUniforms {
    vec4 _u_slot0; // [origin_x, origin_y, res_w, res_h]
    vec4 _u_slot1; // [viewport_w, viewport_h, opacity, u_time]
    vec4 _u_slot2; // [u_speed, u_scale, u_distortion, u_swirl]
    vec4 _u_slot3; // [u_direction, u_grain, 0, 0]
};
layout(location = 0) out vec4 _cst_outColor;
#define u_resolution (_u_slot0.zw)
#define u_time (_u_slot1.w)
#define u_speed (_u_slot2.x)
#define u_scale (_u_slot2.y)
#define u_distortion (_u_slot2.z)
#define u_swirl (_u_slot2.w)
#define u_direction (_u_slot3.x)
#define u_grain (_u_slot3.y)
"#,
            "_u_slot1.z",
        ),
        "blue-hour.glsl" => (
            r#"#version 450
layout(std140, set = 0, binding = 0) uniform CstUniforms {
    vec4 _u_slot0; // [origin_x, origin_y, res_w, res_h]
    vec4 _u_slot1; // [viewport_w, viewport_h, opacity, u_time]
    vec4 _u_slot2; // [u_speed, u_phase, u_count, u_height]
    vec4 _u_slot3; // [u_focus, u_position, u_blend, u_facets]
    vec4 _u_slot4; // [u_grain, 0, 0, 0]
};
layout(set = 0, binding = 1) uniform texture2D _u_palette_tex;
layout(set = 0, binding = 2) uniform sampler _u_palette_smp;
layout(location = 0) out vec4 _cst_outColor;
#define u_resolution (_u_slot0.zw)
#define u_time (_u_slot1.w)
#define u_speed (_u_slot2.x)
#define u_phase (_u_slot2.y)
#define u_count (_u_slot2.z)
#define u_height (_u_slot2.w)
#define u_focus (_u_slot3.x)
#define u_position (_u_slot3.y)
#define u_blend (_u_slot3.z)
#define u_facets (_u_slot3.w)
#define u_grain (_u_slot4.x)
vec4 _cst_sample_palette(vec2 uv) {
    return texture(sampler2D(_u_palette_tex, _u_palette_smp), vec2(uv.x, 0.5));
}
"#,
            "_u_slot1.z",
        ),
        "frosted-glass.glsl" => (
            r#"#version 450
layout(std140, set = 0, binding = 0) uniform CstUniforms {
    vec4 _u_slot0; // [origin_x, origin_y, res_w, res_h]
    vec4 _u_slot1; // [viewport_w, viewport_h, opacity, 0]
    vec4 _u_slot2; // [u_blur, u_refract, u_vibrancy, u_grain]
    vec4 _u_slot3; // [u_tint.r, u_tint.g, u_tint.b, u_tintOpacity]
    vec4 _u_slot4; // [u_specular, cap_offset_x, cap_offset_y, 0]
    vec4 _u_slot5; // [cap_w, cap_h, alloc_w, alloc_h]
};
layout(set = 0, binding = 1) uniform texture2D _u_sdf_tex;
layout(set = 0, binding = 2) uniform sampler _u_sdf_smp;
layout(set = 0, binding = 3) uniform texture2D _u_bg_tex;
layout(set = 0, binding = 4) uniform sampler _u_bg_smp;
layout(location = 0) out vec4 _cst_outColor;
#define u_resolution (_u_slot0.zw)
#define u_blur (_u_slot2.x)
#define u_refract (_u_slot2.y)
#define u_vibrancy (_u_slot2.z)
#define u_grain (_u_slot2.w)
#define u_tint (_u_slot3.xyz)
#define u_tintOpacity (_u_slot3.w)
#define u_specular (_u_slot4.x)
vec4 _cst_sample_sdf(vec2 uv) {
    return texture(sampler2D(_u_sdf_tex, _u_sdf_smp), vec2(uv.x, 1.0 - uv.y));
}
vec4 _cst_sample_bg(vec2 uv) {
    vec2 topDown = vec2(uv.x, 1.0 - uv.y);
    vec2 pxInCap = _u_slot4.yz + topDown * max(_u_slot0.zw, vec2(1.0));
    vec2 clampedPx = clamp(pxInCap, vec2(0.5), max(_u_slot5.xy - vec2(0.5), vec2(0.5)));
    vec2 texUv = clampedPx / max(_u_slot5.zw, vec2(1.0));
    return texture(sampler2D(_u_bg_tex, _u_bg_smp), texUv);
}
"#,
            "_u_slot1.z * _cst_sample_sdf(_cst_fragCoord.xy / max(u_resolution, vec2(1.0))).a",
        ),
        other => panic!("shader {other} is not in WHITELISTED_SHADERS"),
    };

    let mut body = stripped
        .replace("texture2D(u_palette,", "_cst_sample_palette(")
        .replace("texture2D(u_sdf,", "_cst_sample_sdf(")
        .replace("texture2D(u_bg,", "_cst_sample_bg(")
        .replace("gl_FragCoord", "_cst_fragCoord")
        .replace("gl_FragColor", "_cst_fragColor");

    let main_target = "void main() {";
    let main_pos = body
        .find(main_target)
        .unwrap_or_else(|| panic!("{file_name} missing `void main() {{`"));
    let main_open_end = main_pos + main_target.len();
    let main_close = body
        .rfind('}')
        .unwrap_or_else(|| panic!("{file_name} missing closing `}}`"));

    let injected_prologue = "\n    vec4 _cst_fragCoord = vec4(gl_FragCoord.x - _u_slot0.x, _u_slot0.w - (gl_FragCoord.y - _u_slot0.y), gl_FragCoord.z, gl_FragCoord.w);\n    vec4 _cst_fragColor = vec4(0.0);\n";
    let injected_epilogue = format!(
        "\n    _cst_outColor = vec4(_cst_fragColor.rgb, clamp(_cst_fragColor.a * ({footer_alpha_expr}), 0.0, 1.0));\n}}"
    );

    body.replace_range(main_close..=main_close, &injected_epilogue);
    body.insert_str(main_open_end, injected_prologue);

    format!("{header}\n{body}\n")
}

fn translate_glsl450_to_hlsl50(file_name: &str, glsl_450: &str) -> String {
    use naga::back::hlsl;
    use naga::front::glsl;
    use naga::valid::{Capabilities, ValidationFlags, Validator};

    let mut frontend = glsl::Frontend::default();
    let options = glsl::Options::from(naga::ShaderStage::Fragment);
    let module = frontend
        .parse(&options, glsl_450)
        .unwrap_or_else(|errs| panic!("naga GLSL parse failed for {file_name}: {errs:?}"));

    let info = Validator::new(ValidationFlags::all(), Capabilities::empty())
        .validate(&module)
        .unwrap_or_else(|e| panic!("naga validation failed for {file_name}: {e:?}"));

    let mut binding_map = hlsl::BindingMap::new();
    // Uniform buffer `set=0, binding=0` -> `cbuffer b0`
    binding_map.insert(
        naga::ResourceBinding {
            group: 0,
            binding: 0,
        },
        hlsl::BindTarget {
            space: 0,
            register: 0,
            binding_array_size: None,
            dynamic_storage_buffer_offsets_index: None,
            restrict_indexing: false,
        },
    );
    // Texture/sampler pairs:
    // binding 1 -> t0, binding 2 -> s0
    // binding 3 -> t1, binding 4 -> s1
    for pair_idx in 0..2u32 {
        binding_map.insert(
            naga::ResourceBinding {
                group: 0,
                binding: 1 + pair_idx * 2,
            },
            hlsl::BindTarget {
                space: 0,
                register: pair_idx,
                binding_array_size: None,
                dynamic_storage_buffer_offsets_index: None,
                restrict_indexing: false,
            },
        );
        binding_map.insert(
            naga::ResourceBinding {
                group: 0,
                binding: 2 + pair_idx * 2,
            },
            hlsl::BindTarget {
                space: 0,
                register: pair_idx,
                binding_array_size: None,
                dynamic_storage_buffer_offsets_index: None,
                restrict_indexing: false,
            },
        );
    }

    let mut sampler_buffer_binding_map = hlsl::SamplerIndexBufferBindingMap::new();
    sampler_buffer_binding_map.insert(
        hlsl::SamplerIndexBufferKey { group: 0 },
        hlsl::BindTarget {
            space: 250,
            register: 99,
            binding_array_size: None,
            dynamic_storage_buffer_offsets_index: None,
            restrict_indexing: false,
        },
    );

    let hlsl_options = hlsl::Options {
        shader_model: hlsl::ShaderModel::V5_0,
        binding_map,
        sampler_buffer_binding_map,
        fake_missing_bindings: false,
        restrict_indexing: false,
        force_loop_bounding: false,
        ..hlsl::Options::default()
    };
    let pipeline_options = hlsl::PipelineOptions::default();

    let mut hlsl_source = String::new();
    let mut writer = hlsl::Writer::new(&mut hlsl_source, &hlsl_options, &pipeline_options);
    writer
        .write(&module, &info, None)
        .unwrap_or_else(|e| panic!("naga HLSL write failed for {file_name}: {e:?}"));

    lower_naga_d3d12_samplers_to_d3d11_sm50(&hlsl_source)
}

/// Lowers Naga 30's D3D12 descriptor-heap sampler indirection & `space0` qualifiers
/// into pure Direct3D 11 Shader Model 5.0 `SamplerState : register(s0/s1)`.
fn lower_naga_d3d12_samplers_to_d3d11_sm50(raw_hlsl: &str) -> String {
    let mut lines = Vec::new();
    let mut emitted_samplers = false;
    for line in raw_hlsl.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("SamplerState nagaSamplerHeap")
            || trimmed.starts_with("SamplerComparisonState nagaComparisonSamplerHeap")
            || trimmed.contains("nagaGroup0SamplerIndexArray : register(")
        {
            if !emitted_samplers {
                lines.push("SamplerState _cst_sampler0 : register(s0);".to_owned());
                lines.push("SamplerState _cst_sampler1 : register(s1);".to_owned());
                emitted_samplers = true;
            }
            continue;
        }
        let cleaned = line
            .replace(
                "nagaSamplerHeap[nagaGroup0SamplerIndexArray[0u]]",
                "_cst_sampler0",
            )
            .replace(
                "nagaSamplerHeap[nagaGroup0SamplerIndexArray[0]]",
                "_cst_sampler0",
            )
            .replace(
                "nagaSamplerHeap[nagaGroup0SamplerIndexArray[1u]]",
                "_cst_sampler1",
            )
            .replace(
                "nagaSamplerHeap[nagaGroup0SamplerIndexArray[1]]",
                "_cst_sampler1",
            )
            .replace(", space0)", ")");
        lines.push(cleaned);
    }
    lines.join("\n")
}

#[cfg(windows)]
fn d3d_compile_hlsl(hlsl: &str, entry: &str, target: &str, source_name: &str) -> Vec<u8> {
    use std::ffi::CString;
    use windows::Win32::Graphics::Direct3D::Fxc::{D3DCOMPILE_OPTIMIZATION_LEVEL3, D3DCompile};
    use windows::Win32::Graphics::Direct3D::ID3DBlob;
    use windows::core::PCSTR;

    let src_name_c = CString::new(source_name).unwrap();
    let entry_c = CString::new(entry).unwrap();
    let target_c = CString::new(target).unwrap();

    let mut code_blob: Option<ID3DBlob> = None;
    let mut err_blob: Option<ID3DBlob> = None;

    let hr = unsafe {
        D3DCompile(
            hlsl.as_ptr().cast(),
            hlsl.len(),
            PCSTR(src_name_c.as_ptr().cast()),
            None,
            None,
            PCSTR(entry_c.as_ptr().cast()),
            PCSTR(target_c.as_ptr().cast()),
            D3DCOMPILE_OPTIMIZATION_LEVEL3,
            0,
            &mut code_blob,
            Some(&mut err_blob),
        )
    };

    if let Err(err) = hr {
        let diag = err_blob
            .as_ref()
            .map(|b| unsafe {
                let slice = std::slice::from_raw_parts(
                    b.GetBufferPointer().cast::<u8>(),
                    b.GetBufferSize(),
                );
                String::from_utf8_lossy(slice).into_owned()
            })
            .unwrap_or_default();
        panic!(
            "D3DCompile failed for {source_name} ({entry} / {target}): {err}\n{diag}\nHLSL:\n{hlsl}"
        );
    }

    let blob = code_blob.expect("D3DCompile succeeded without blob");
    unsafe {
        std::slice::from_raw_parts(blob.GetBufferPointer().cast::<u8>(), blob.GetBufferSize())
            .to_vec()
    }
}

#[cfg(not(windows))]
fn d3d_compile_hlsl(_hlsl: &str, _entry: &str, _target: &str, _source_name: &str) -> Vec<u8> {
    let mut stub = b"DXBC".to_vec();
    stub.resize(32, 0);
    stub
}

#[cfg(windows)]
fn embed_windows_resources(repo_root: &Path, out_dir: &Path) {
    let logo_png_path = repo_root.join("assets/logo.png");
    println!("cargo:rerun-if-changed={}", logo_png_path.display());

    let require_admin = std::env::var_os("CARGO_FEATURE_ADMIN_MANIFEST").is_some()
        || std::env::var("CST_MANIFEST_REQUIRE_ADMIN").as_deref() == Ok("1");
    let exec_level = if require_admin {
        "requireAdministrator"
    } else {
        "asInvoker"
    };

    let manifest_xml = format!(
        r#"<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">
    <trustInfo xmlns="urn:schemas-microsoft-com:asm.v3">
        <security>
            <requestedPrivileges>
                <requestedExecutionLevel level="{exec_level}" uiAccess="false" />
            </requestedPrivileges>
        </security>
    </trustInfo>
    <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">
        <application>
            <supportedOS Id="{{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}}" />
        </application>
    </compatibility>
    <application xmlns="urn:schemas-microsoft-com:asm.v3">
        <windowsSettings>
            <dpiAware xmlns="http://schemas.microsoft.com/SMI/2005/WindowsSettings">true/pm</dpiAware>
            <dpiAwareness xmlns="http://schemas.microsoft.com/SMI/2016/WindowsSettings">PerMonitorV2</dpiAwareness>
            <heapType xmlns="http://schemas.microsoft.com/SMI/2020/WindowsSettings">SegmentHeap</heapType>
        </windowsSettings>
    </application>
    <dependency>
        <dependentAssembly>
            <assemblyIdentity
                type="win32"
                name="Microsoft.Windows.Common-Controls"
                version="6.0.0.0"
                processorArchitecture="*"
                publicKeyToken="6595b64144ccf1df"
            />
        </dependentAssembly>
    </dependency>
</assembly>
"#
    );

    let manifest_path = out_dir.join("cst-pilot.manifest.xml");
    fs::write(&manifest_path, manifest_xml).expect("write cst-pilot.manifest.xml");

    let mut rc_content =
        String::from("#define RT_MANIFEST 24\n1 RT_MANIFEST \"cst-pilot.manifest.xml\"\n");
    if let Ok(png_bytes) = fs::read(&logo_png_path)
        && png_bytes.starts_with(&[0x89, b'P', b'N', b'G', 0x0D, 0x0A, 0x1A, 0x0A])
    {
        let ico_bytes = wrap_png_as_ico(&png_bytes);
        let ico_path = out_dir.join("cst-pilot.ico");
        fs::write(&ico_path, ico_bytes).expect("write cst-pilot.ico");
        rc_content.push_str("1 ICON \"cst-pilot.ico\"\n");
    }

    let rc_path = out_dir.join("cst-pilot.rc");
    fs::write(&rc_path, rc_content).expect("write cst-pilot.rc");

    embed_resource::compile(&rc_path, embed_resource::NONE)
        .manifest_required()
        .expect("embed cst-pilot Windows manifest & icon");
}

#[cfg(windows)]
fn wrap_png_as_ico(png_bytes: &[u8]) -> Vec<u8> {
    // Parse IHDR width/height (bytes 16..24 big-endian u32; >= 256 encoded as 0 in ICONDIRENTRY)
    let (w_byte, h_byte) = if png_bytes.len() >= 24 {
        let w = u32::from_be_bytes([png_bytes[16], png_bytes[17], png_bytes[18], png_bytes[19]]);
        let h = u32::from_be_bytes([png_bytes[20], png_bytes[21], png_bytes[22], png_bytes[23]]);
        (
            if w >= 256 { 0u8 } else { w as u8 },
            if h >= 256 { 0u8 } else { h as u8 },
        )
    } else {
        (0u8, 0u8)
    };
    let mut ico = Vec::with_capacity(22 + png_bytes.len());
    // ICONDIR: reserved=0, type=1 (icon), count=1
    ico.extend_from_slice(&0u16.to_le_bytes());
    ico.extend_from_slice(&1u16.to_le_bytes());
    ico.extend_from_slice(&1u16.to_le_bytes());
    // ICONDIRENTRY (16 bytes)
    ico.push(w_byte);
    ico.push(h_byte);
    ico.push(0); // color count
    ico.push(0); // reserved
    ico.extend_from_slice(&1u16.to_le_bytes()); // color planes
    ico.extend_from_slice(&32u16.to_le_bytes()); // bits per pixel
    ico.extend_from_slice(&(png_bytes.len() as u32).to_le_bytes());
    ico.extend_from_slice(&22u32.to_le_bytes()); // offset to PNG payload
    ico.extend_from_slice(png_bytes);
    ico
}
